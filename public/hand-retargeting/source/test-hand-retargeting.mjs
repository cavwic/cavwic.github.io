import assert from 'node:assert/strict';
import { forwardKinematics, fingerKinematics, fingerJacobian, jointLimits, sampleGesture, normalizeLandmarks, angleBaseline, solveIK, metrics, padFacing, benchmark, gestureNames, robotModel, humanModel, landmarkChains, syntheticPinchReferenceMm, modelKinematicsId } from '../src/features/hand-retargeting/engine.ts';

const distance = (a, b) => Math.hypot(...a.map((v, i) => v - b[i]));
const maximum = values => Math.max(...values);
const valid = q => q.length === 20 && q.every(Number.isFinite);
const gap = points => distance(points[4], points[8]) * 1000;
const sub = (a, b) => a.map((v, i) => v - b[i]);
const dot = (a, b) => a.reduce((sum, v, i) => sum + v * b[i], 0);
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const unit = v => v.map(x => x / Math.hypot(...v));
const q = jointLimits.map((limit, i) => limit.min + (limit.max - limit.min) * (.3 + .1 * Math.sin(i)));
const points = forwardKinematics(q);
assert.equal(points.length, 21);
assert(points.flat().every(Number.isFinite));

// Analytic Jacobian checked against central differences, every joint/chain point.
let jacobianError = 0;
const opposedFixture = jointLimits.map((limit, i) => limit.min + (limit.max - limit.min) * (.6 + .25 * Math.cos(i)));
for (const fixture of [q, opposedFixture]) for (let f = 0; f < 5; f++) for (let p = 0; p <= 3; p++) {
  const jac = fingerJacobian(fixture, f, p);
  for (let j = 0; j < 4; j++) {
    const a = [...fixture], b = [...fixture], eps = 1e-6;
    a[f * 4 + j] += eps; b[f * 4 + j] -= eps;
    const pa = forwardKinematics(a)[f * 4 + p + 1], pb = forwardKinematics(b)[f * 4 + p + 1];
    for (let axis = 0; axis < 3; axis++) jacobianError = Math.max(jacobianError, Math.abs(jac[axis][j] - (pa[axis] - pb[axis]) / (2 * eps)));
  }
}
assert(jacobianError < 1e-8, `Jacobian error ${jacobianError}`);

// Direction is defined in the kinematic palm frame, not by renderer mirroring:
// +x radial, +y distal, +z palmar. Positive opposition approaches the index;
// CMC flexion enters the palmar half-space from neutral. Once opposed,
// distal thumb flexion curls radially inward, not in the index curl plane.
const neutral = Array(20).fill(0), neutralPoints = forwardKinematics(neutral);
const opposition = [...neutral]; opposition[0] = .35;
const opposedPoints = forwardKinematics(opposition);
assert(opposedPoints[4][0] < neutralPoints[4][0]);
assert(gap(opposedPoints) < gap(neutralPoints));
for (const joint of [1, 2, 3]) {
  const flexed = [...neutral]; flexed[joint] = .3;
  assert(forwardKinematics(flexed)[4][2] > neutralPoints[4][2] + .004);
}
const indexFlexed = [...neutral]; indexFlexed[5] = .3;
assert(forwardKinematics(indexFlexed)[8][2] > 0);
assert.equal(robotModel.mounts[0][0], 0); // no former fixed 20-degree thumb tilt
assert(robotModel.thumbTwistRatio < 0);
assert.equal(modelKinematicsId, 'thumb-opposition-v2-palmar-canonical');
const opposedThumb = [...neutral]; opposedThumb[0] = .7; opposedThumb[1] = .3;
const beforeThumbCurl = forwardKinematics(opposedThumb);
for (const joint of [2, 3]) for (const angle of [.2, .4, .6]) {
  const curled = [...opposedThumb]; curled[joint] = angle;
  const after = forwardKinematics(curled);
  // This is an independent geometric direction requirement in canonical
  // coordinates: the index lies on the thumb's negative-x side here.
  assert(after[4][0] < beforeThumbCurl[4][0] - .004);
  assert(gap(after) < gap(beforeThumbCurl));
}
const thumbState = fingerKinematics(opposedThumb, 0);
assert(Math.abs(dot(thumbState.axes[1], thumbState.axes[2])) < .4);
// Every visible bone receives a full orthonormal frame, including roll.
for (let f = 0; f < 5; f++) {
  const state = fingerKinematics(q, f);
  assert.equal(state.rotations.length, 3);
  for (let bone = 0; bone < 3; bone++) {
    const r = state.rotations[bone], columns = [0, 1, 2].map(c => [r[c], r[3 + c], r[6 + c]]);
    assert(distance(columns[1], unit(sub(state.points[bone + 1], state.points[bone]))) < 1e-12);
    for (let j = 0; j < 3; j++) for (let k = 0; k < 3; k++) assert(Math.abs(dot(columns[j], columns[k]) - Number(j === k)) < 1e-12);
    assert(distance(cross(columns[0], columns[1]), columns[2]) < 1e-12);
  }
}

// Independent marker fixture, NOT generated by this FK: an actual right
// hand lies palm-down, distal is world +y, radial is world -x and marked
// palmar bends are world -z. This fixes anatomy/hand-side sign externally
// instead of calling the same FK a source of anatomical ground truth.
const rightPalmDown = [
  [0, 0, 0], [-.043, .030, 0], [-.065, .055, 0], [-.064, .072, -.012], [-.058, .082, -.028],
  [-.030, .080, 0], [-.030, .120, 0], [-.030, .138, -.018], [-.030, .135, -.038],
  [0, .087, 0], [0, .132, 0], [0, .152, -.020], [0, .148, -.043],
  [.024, .081, 0], [.024, .122, 0], [.024, .140, -.019], [.024, .136, -.039],
  [.044, .068, 0], [.044, .100, 0], [.044, .116, -.015], [.044, .112, -.032],
];
const independentRight = normalizeLandmarks(rightPalmDown, 'Right');
assert(independentRight.valid);
assert(independentRight.points[4][0] > 0);
assert(independentRight.points[8][2] > 0 && independentRight.points[12][2] > 0);
const independentLeft = normalizeLandmarks(rightPalmDown.map(([x, y, z]) => [-x, y, z]), 'Left');
assert(independentLeft.valid);
assert(maximum(independentRight.points.map((p, i) => distance(p, independentLeft.points[i]))) < 1e-12);

// The coupled task-vector Jacobian is J_thumb - J_index, with no handedness
// sign hack. Verify all eight derivatives independently.
const jt = fingerJacobian(q, 0), ji = fingerJacobian(q, 1);
for (let j = 0; j < 8; j++) {
  const a = [...q], b = [...q], eps = 1e-6;
  a[j] += eps; b[j] -= eps;
  const pa = forwardKinematics(a), pb = forwardKinematics(b);
  for (let axis = 0; axis < 3; axis++) {
    const numeric = ((pa[4][axis] - pa[8][axis]) - (pb[4][axis] - pb[8][axis])) / (2 * eps);
    const analytic = j < 4 ? jt[axis][j] : -ji[axis][j - 4];
    assert(Math.abs(numeric - analytic) < 1e-8);
  }
}

// Frame fit invariant to rigid rotation, translation and uniform scale.
const sample = sampleGesture('pinch', 1.3);
const canonical = normalizeLandmarks(sample).points;
const a = .63, b = -.42;
const rotate = ([x, y, z]) => {
  const x1 = x * Math.cos(a) - y * Math.sin(a), y1 = x * Math.sin(a) + y * Math.cos(a);
  return [x1, y1 * Math.cos(b) - z * Math.sin(b), y1 * Math.sin(b) + z * Math.cos(b)];
};
const transformed = sample.map(p => rotate(p).map((v, i) => v * 1.8 + [2, -3, .5][i]));
const recovered = normalizeLandmarks(transformed).points;
assert(maximum(canonical.map((p, i) => distance(p, recovered[i]))) < 1e-10);
const mirrored = sample.map(([x, y, z]) => [-x, y, z]);
const left = normalizeLandmarks(mirrored, 'Left').points;
assert(maximum(canonical.map((p, i) => distance(p, left[i]))) < 1e-10);
assert(maximum(solveIK(canonical).q.map((v, i) => Math.abs(v - solveIK(left).q[i]))) < 1e-8);
assert.equal(normalizeLandmarks(Array.from({ length: 21 }, () => [0, 0, 0])).valid, false);
assert.equal(normalizeLandmarks([[NaN, 0, 0]]).valid, false);

// Same morphology FK->IK is a numerical self-test, not a human generalization claim.
const base = angleBaseline(points);
assert(maximum(q.map((v, i) => Math.abs(v - base[i]))) < 1e-10);
const opposedRecovered = angleBaseline(forwardKinematics(opposedFixture));
assert(maximum(opposedFixture.map((v, i) => Math.abs(v - opposedRecovered[i]))) < 1e-9);
const reachable = solveIK(points, undefined, { postureWeight: 0, temporalWeight: 0 });
assert(valid(reachable.q));
assert.equal(reachable.status, 'converged');
assert(reachable.metrics.maxTipErrorMm < .01);
assert.equal(reachable.metrics.limitViolations, 0);
assert.equal(reachable.fallbackAttempts, 0);

// An axial target shorter than a straight finger has zero first-order
// gradient at q=0. The limited deterministic fallback must escape that
// stationary initial state without moving the original targets.
const shortenedInput = forwardKinematics(Array(20).fill(0));
for (let i = 6; i <= 8; i++) shortenedInput[i] = shortenedInput[i].map((v, axis) => shortenedInput[5][axis] + .75 * (v - shortenedInput[5][axis]));
const unchangedInput = structuredClone(shortenedInput);
const straightResidualMm = metrics(Array(20).fill(0), shortenedInput).tipErrorsMm[1];
const escaped = solveIK(shortenedInput, undefined, { enforceLimits: false, temporalWeight: 0 });
assert.equal(escaped.fallbackAttempts, 2);
assert(escaped.metrics.tipErrorsMm[1] < straightResidualMm * .1);
assert(escaped.objective < .004);
assert(valid(escaped.q));
assert.deepEqual(shortenedInput, unchangedInput);
const escapedAgain = solveIK(shortenedInput, undefined, { enforceLimits: false, temporalWeight: 0 });
assert.deepEqual(escaped.q, escapedAgain.q);
const boundedEscape = solveIK(shortenedInput, undefined, { enforceLimits: true });
assert.equal(boundedEscape.metrics.limitViolations, 0);
assert(valid(boundedEscape.q));
// Longer-than-chain targets and ordinary changing poses must not pay for
// retries. Their true residuals remain visible.
assert.equal(solveIK(normalizeLandmarks(sampleGesture('open', 1)).points).fallbackAttempts, 0);
assert.equal(solveIK(normalizeLandmarks(sampleGesture('fist', 1)).points).fallbackAttempts, 0);

// The closed synthetic reference has a nonzero, explicit ~8 mm keypoint
// clearance. All source bones remain the FK model's fixed lengths.
const closedPinch = normalizeLandmarks(sampleGesture('pinch', 1)).points;
assert(Math.abs(gap(closedPinch) - syntheticPinchReferenceMm) < .01);
// Independently derive each designed source's concave normal from bone
// directions; a small centre gap alone must not pass as opposing pads.
const sourceNormals = [0, 1].map(f => {
  const chain = landmarkChains[f], segments = [0, 1, 2].map(j => unit(sub(closedPinch[chain[j + 1]], closedPinch[chain[j]])));
  return unit(cross(unit(cross(segments[0], segments[1])), segments[2]));
});
const sourceTowardIndex = unit(sub(closedPinch[8], closedPinch[4]));
assert(dot(sourceNormals[0], sourceTowardIndex) > .7);
assert(-dot(sourceNormals[1], sourceTowardIndex) > .7);
assert(dot(sourceNormals[0], sourceNormals[1]) < -.15);
// The closed reference itself must show visible MCP/IP curvature; keeping
// these nearly zero would hide a curl-plane regression in the main demo.
const thumbSegments = [0, 1, 2].map(j => unit(sub(closedPinch[j + 2], closedPinch[j + 1])));
const thumbMcpBendRad = Math.acos(Math.max(-1, Math.min(1, dot(thumbSegments[0], thumbSegments[1]))));
const thumbIpBendRad = Math.acos(Math.max(-1, Math.min(1, dot(thumbSegments[1], thumbSegments[2]))));
assert(thumbMcpBendRad >= .2);
assert(thumbIpBendRad >= .1);
for (let i = 0; i < 60; i++) {
  const raw = sampleGesture('pinch', i / 15);
  assert(gap(normalizeLandmarks(raw).points) >= syntheticPinchReferenceMm - .01);
  for (let f = 0; f < 5; f++) for (let bone = 0; bone < 3; bone++) {
    const chain = landmarkChains[f];
    assert(Math.abs(distance(raw[chain[bone]], raw[chain[bone + 1]]) - humanModel.lengths[f][bone]) < 1e-12);
  }
}
