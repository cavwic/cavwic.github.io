// Per-chain base alignment must not silently erase a zero-gap input task.
// This is a constructive invariance test, not a recorded anatomical pose.
const thumbShift = closedPinch[8].map((v, axis) => v - closedPinch[4][axis]);
const zeroGap = closedPinch.map((p, i) => i > 0 && i < 5 ? p.map((v, axis) => v + thumbShift[axis]) : [...p]);
